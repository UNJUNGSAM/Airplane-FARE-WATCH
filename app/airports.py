_DEFAULT = {"city": None, "country": "기타", "flag": "🌍"}


def airport_info(code: str) -> dict[str, Any]:
    """IATA 코드의 도시/국가/국기 정보. 미등록 코드는 코드명 그대로 반환."""
    info = _AIRPORTS.get((code or "").upper())
    if info is None:
        return {"city": (code or "?").upper(), "country": "기타", "flag": "🌍"}
    return {"city": info[0], "country": info[1], "flag": info[2]}


def destination_label(code: str) -> str:
    """표시용 라벨: '다낭(DAD)' 형태."""
    info = airport_info(code)
    city = info["city"] or code.upper()
    return f"{city} ({code.upper()})"


def get_airport_choices() -> list[str]:
    """검색 및 선택용 공항 목록 (한국 공항 상단, 그 외 국가/도시 순)."""
    korea = []
    others = []
    for code, (city, country, flag) in _AIRPORTS.items():
        entry = f"{code} · {city} ({country}) {flag}"
        if country == "대한민국":
            korea.append((code, entry))
        else:
            others.append((country, city, entry))

    # 대한민국 공항 정렬 (인천, 김포 우선)
    priority = {"ICN": 0, "GMP": 1, "PUS": 2, "CJU": 3}
    korea.sort(key=lambda x: priority.get(x[0], 99))
    others.sort(key=lambda x: (x[0], x[1]))

    return [x[1] for x in korea] + [x[2] for x in others] + ["DIRECT · 직접 입력"]


def choice_from_code(code: str | None) -> str:
    """IATA 코드 → selectbox 표시 문자열 매핑."""
    if not code:
        return "ICN · 인천 (대한민국) 🇰🇷"
    code = code.upper().strip()
    if code in _AIRPORTS:
        city, country, flag = _AIRPORTS[code]
        return f"{code} · {city} ({country}) {flag}"
    return "DIRECT · 직접 입력"


def code_from_choice(choice: str) -> str:
    """selectbox 선택 항목 → IATA 코드 추출."""
    if not choice or choice.startswith("DIRECT"):
        return ""
    return choice.split(" · ", 1)[0].strip().upper()
